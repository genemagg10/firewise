/* Shared data loader + helpers for all pages.
   Public data (meta, events) and the ENCRYPTED residents blob come from data/public-data.js
   (window.FIREWISE_PUBLIC), generated by tools/build_data.py. Falls back to fetching data/*.json.
   Residents are AES-256-GCM encrypted; the key is derived from the site password with PBKDF2-SHA256
   in the browser (WebCrypto) and kept in sessionStorage only for this browser tab/session. */
(function () {
  const STATUS = {
    signed:   { label: "Signed up",           color: "#1a7f37" },
    attended: { label: "Attended past event", color: "#1f5fa8" },
    noresp:   { label: "No response / not signed up", color: "#c2410c" },
    unknown:  { label: "Unknown",             color: "#8b949e" },
  };
  // one status per home: signed up wins; else attended a past event; else explicit "no"; else unknown.
  function statusOf(r) {
    if (r.signed_up === "yes") return "signed";
    if (r.events_attended && r.events_attended.length) return "attended";
    if (r.signed_up === "no") return "noresp";
    return "unknown";
  }
  const esc = s => String(s ?? "").replace(/[&<>"']/g, ch => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[ch]));
  const b64d = s => Uint8Array.from(atob(s), c => c.charCodeAt(0));
  const b64e = b => btoa(String.fromCharCode(...new Uint8Array(b)));

  async function loadPublic() {
    if (window.FIREWISE_PUBLIC) return window.FIREWISE_PUBLIC;
    const [events, enc] = await Promise.all([
      fetch("data/events.json").then(r => r.json()).catch(() => []),
      fetch("data/residents.enc.json").then(r => r.json()).catch(() => null)]);
    return { meta: { sheet_total: 198 }, events, residents_enc: enc };
  }

  // ---- crypto ----
  const keyName = env => "firewise-key-" + env.salt;   // salt changes each build -> old keys stop matching
  async function deriveKey(password, env) {
    const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(password), "PBKDF2", false, ["deriveKey"]);
    return crypto.subtle.deriveKey({ name: "PBKDF2", hash: "SHA-256", salt: b64d(env.salt), iterations: env.iterations },
      base, { name: "AES-GCM", length: 256 }, true, ["decrypt"]);
  }
  async function decryptWith(key, env) {
    const pt = await crypto.subtle.decrypt({ name: "AES-GCM", iv: b64d(env.iv) }, key, b64d(env.ciphertext));
    return JSON.parse(new TextDecoder().decode(pt));
  }
  async function trySessionKey(env) {
    const raw = sessionStorage.getItem(keyName(env));
    if (!raw) return null;
    try {
      const key = await crypto.subtle.importKey("raw", b64d(raw), { name: "AES-GCM" }, false, ["decrypt"]);
      return await decryptWith(key, env);
    } catch (e) { sessionStorage.removeItem(keyName(env)); return null; }
  }
  async function unlock(password, env) {
    const key = await deriveKey(password, env);
    const data = await decryptWith(key, env);          // throws on wrong password (GCM auth tag mismatch)
    sessionStorage.setItem(keyName(env), b64e(await crypto.subtle.exportKey("raw", key)));
    return data;
  }
  const UI_KEY = "firewise-ui";
  function markAdmin() { sessionStorage.setItem(UI_KEY, "admin"); }
  function lock() {
    sessionStorage.removeItem(UI_KEY);
    Object.keys(sessionStorage).filter(k => k.startsWith("firewise-key-")).forEach(k => sessionStorage.removeItem(k));
    location.href = "index.html";
  }
  function viewPublic() {
    sessionStorage.removeItem(UI_KEY);
    location.href = "index.html";
  }

  // ---- lock screen ----
  function showLockScreen(env, { dismissable = false } = {}) {
    return new Promise((resolve, reject) => {
      document.querySelectorAll(".lock-overlay").forEach(n => n.remove());
      const wrap = document.createElement("div");
      wrap.className = "lock-overlay";
      wrap.innerHTML = `
        <div class="lock-card" role="dialog" aria-modal="true" aria-labelledby="lock-title" aria-describedby="lock-desc">
          <div class="lock-icon" aria-hidden="true">&#128274;</div>
          <h2 id="lock-title">Organizer sign-in</h2>
          <p id="lock-desc">Household names, emails, and the map are encrypted. Enter the site password to open organizer tools for this browser session.</p>
          <form>
            <label for="lock-pw">Password</label>
            <input id="lock-pw" type="password" autocomplete="current-password" required>
            <p class="lock-error" id="lock-err" role="alert" aria-live="assertive"></p>
            <div class="lock-actions">
              <button class="btn" type="submit">Unlock</button>
              ${dismissable ? '<button class="btn secondary" type="button" data-cancel>Not now</button>' : '<a class="btn secondary" href="index.html">Community site</a>'}
            </div>
          </form>
          <p class="lock-note">The community site is public. Need the password? Ask a neighborhood organizer.</p>
        </div>`;
      document.body.appendChild(wrap);
      document.body.classList.add("locked");
      const form = wrap.querySelector("form"), input = wrap.querySelector("#lock-pw"), err = wrap.querySelector(".lock-error"),
            btn = wrap.querySelector("button[type=submit]");
      input.setAttribute("aria-describedby", "lock-desc lock-err");
      const close = (how) => {
        document.removeEventListener("keydown", onKey);
        wrap.remove();
        document.body.classList.remove("locked");
        if (how === "ok") return;
        reject(new Error("locked"));
      };
      function onKey(ev) { if (ev.key === "Escape" && dismissable) close("cancel"); }
      document.addEventListener("keydown", onKey);
      setTimeout(() => input.focus(), 30);
      form.addEventListener("submit", async ev => {
        ev.preventDefault(); err.textContent = ""; input.removeAttribute("aria-invalid");
        btn.disabled = true; btn.textContent = "Unlocking\u2026";
        try {
          const data = await unlock(input.value, env);
          document.removeEventListener("keydown", onKey);
          wrap.remove(); document.body.classList.remove("locked"); resolve(data);
        } catch (e) {
          err.textContent = "That password didn\u2019t work. Please check it and try again.";
          input.setAttribute("aria-invalid", "true");
          input.select(); btn.disabled = false; btn.textContent = "Unlock";
        }
      });
      const c = wrap.querySelector("[data-cancel]");
      if (c) c.onclick = () => close("cancel");
    });
  }

  function addLockButton() {
    const ul = document.querySelector("nav.main ul");
    if (!ul || ul.querySelector(".lock-link")) return;
    ul.insertAdjacentHTML("beforeend", '<li><button type="button" class="lock-link" title="Lock and return to the community site">Lock</button></li>');
    ul.querySelector(".lock-link").onclick = lock;
  }

  async function sessionData(env) {
    if (!env) return null;
    const data = await trySessionKey(env);
    if (!data || !data.residents) return null;
    data.residents.forEach(r => { r._status = statusOf(r); r._noinfo = isNoInfo(r); });
    return data;
  }

  async function openAdmin(env) {
    try {
      let blob = env;
      if (!blob && window.FIREWISE_PUBLIC) blob = window.FIREWISE_PUBLIC.residents_enc;
      if (!blob) blob = await fetch("data/residents.enc.json").then(r => r.ok ? r.json() : null).catch(() => null);
      if (!blob) return;
      if (!(await trySessionKey(blob))) await showLockScreen(blob, { dismissable: true });
    } catch (e) { return; }
    markAdmin();
    location.href = "index.html";
  }

  function mountCornerLock(env) {
    const btn = document.getElementById("cornerLock");
    if (!btn || btn.dataset.bound) return;
    btn.dataset.bound = "1";
    btn.addEventListener("click", () => openAdmin(env));
  }

  function parseDay(s) {
    const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s || "");
    return m ? new Date(+m[1], +m[2] - 1, +m[3]) : null;
  }
  function fmtDay(d) {
    return d.toLocaleDateString("en-US", { weekday: "short", month: "short", day: "numeric", year: "numeric" });
  }
  // An event is past the day after its end_date (or date).
  function splitEvents(events, now) {
    const today = now ? new Date(now) : new Date();
    today.setHours(0, 0, 0, 0);
    const isPast = e => { const last = parseDay(e.end_date) || parseDay(e.date); return !!(last && last < today); };
    const byDate = (a, b) => (a.date || "").localeCompare(b.date || "");
    const list = events || [];
    return { upcoming: list.filter(e => !isPast(e)).sort(byDate), past: list.filter(isPast).sort(byDate).reverse() };
  }
  function eventCardHTML(e, past) {
    const d = parseDay(e.date), end = parseDay(e.end_date);
    const when = d ? fmtDay(d) + (end && end > d ? " \u2013 " + fmtDay(end) : "") : esc(e.date);
    return `<article class="card event${past ? " past" : ""}">
      <div class="when">${when}${e.time ? " \u00b7 " + esc(e.time) : ""}${past ? ' <span class="pill unknown">Past</span>' : ""}</div>
      <h3>${esc(e.title)}</h3>
      ${e.location ? `<div class="muted">${esc(e.location)}</div>` : ""}
      ${e.cost ? `<div class="cost">${esc(e.cost)}</div>` : ""}
      <p>${esc(e.description)}</p>
      ${e.organizer ? `<div class="src">${esc(e.organizer)}</div>` : ""}
      ${e.link ? `<a href="${esc(e.link)}" target="_blank" rel="noopener noreferrer">Details</a>` : ""}
    </article>`;
  }

  /* load({ requireResidents: true })  -> prompts until unlocked (map, roster)
     load({ requireResidents: false }) -> residents only if already unlocked this session, else null (overview) */
  /* Email links; each shows its match confidence + evidence on hover, and non-high matches get a small pill. */
  function emailLinks(r) {
    const det = {}; (r.email_details || []).forEach(d => (det[d.email.toLowerCase()] = d));
    return r.emails.map(e => {
      const d = det[e.toLowerCase()];
      const tip = d ? `Match confidence: ${d.confidence}${d.source ? " \u00b7 " + d.source : ""}` : "Entered by an organizer";
      return `<a href="mailto:${esc(e)}" title="${esc(tip)}">${esc(e)}</a>` +
        (d && d.confidence && d.confidence !== "high" ? ` <span class="pill conf-${esc(d.confidence)}" title="${esc(tip)}">${esc(d.confidence)}</span>` : "");
    }).join("<br>");
  }

  async function load({ requireResidents = true } = {}) {
    const pub = await loadPublic();
    const out = { meta: pub.meta || {}, events: pub.events || [], residents: null };
    const env = pub.residents_enc;
    if (!env) { if (requireResidents) throw new Error("Encrypted data not found. Run tools/build_data.py."); return out; }
    let data = await trySessionKey(env);
    if (!data && requireResidents) data = await showLockScreen(env);
    if (data) {
      out.residents = data.residents;
      out.unplaced = data.unplaced_contacts || [];
      out.corrections = data.address_corrections || [];
      out.residents.forEach(r => { r._status = statusOf(r); r._noinfo = isNoInfo(r); });
      markAdmin();
      addLockButton();
    }
    out._env = env;
    return out;
  }

  // "No info at all": nothing known about the household beyond its address and pin.
  function isNoInfo(r) {
    return !r.owner_or_resident_names.length && !r.owner_of_record && !r.emails.length && !r.phone &&
      (r.signed_up || "unknown") === "unknown" && !r.events_attended.length && !r.last_contact && !r.notes;
  }
  // Map colour schemes. "email": has email / no email (+ no-info override); "status": sign-up status.
  const EMAIL_COLORS = { has: { label: "Has an email", color: "#0f9488" }, none: { label: "No email yet", color: "#c9d1d6" } };
  const NOINFO = { label: "No info at all", color: "#ffffff", stroke: "#d1242f" };
  function counts(residents) {
    const c = { total: residents.length, signed: 0, attended: 0, noresp: 0, unknown: 0, anyAttended: 0, signedYes: 0, withEmail: 0, withName: 0, approx: 0, noInfo: 0 };
    residents.forEach(r => {
      c[r._status]++;
      if (r.events_attended.length) c.anyAttended++;
      if (r.signed_up === "yes") c.signedYes++;
      if (r.emails.length) c.withEmail++;
      if (r.owner_or_resident_names.length) c.withName++;
      if (r.approximate) c.approx++;
      if (r._noinfo) c.noInfo++;
    });
    return c;
  }

  function toast(msg) {
    let t = document.querySelector(".toast");
    if (!t) { t = document.createElement("div"); t.className = "toast"; t.setAttribute("role", "status"); t.setAttribute("aria-live", "polite"); document.body.appendChild(t); }
    t.textContent = msg; t.classList.add("show"); clearTimeout(t._h); t._h = setTimeout(() => t.classList.remove("show"), 2600);
  }
  async function copyText(text) {
    try { await navigator.clipboard.writeText(text); return true; }
    catch (e) {
      const ta = document.createElement("textarea"); ta.value = text; ta.style.position = "fixed"; ta.style.opacity = "0";
      document.body.appendChild(ta); ta.select(); let ok = false;
      try { ok = document.execCommand("copy"); } catch (_) {}
      ta.remove(); return ok;
    }
  }
  function setGenerated(meta) {
    const text = (meta && meta.generated) || "";
    document.querySelectorAll("[data-generated], #gen").forEach(el => { el.textContent = text; });
  }

  window.Firewise = { STATUS, EMAIL_COLORS, NOINFO, isNoInfo, statusOf, load, loadPublic, showLockScreen, addLockButton, counts, esc, emailLinks, toast, copyText, setGenerated, lock, viewPublic, openAdmin, mountCornerLock, sessionData, splitEvents, eventCardHTML, markAdmin };
})();
